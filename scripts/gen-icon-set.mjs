#!/usr/bin/env node
/**
 * Regenerate src/components/ds/icon-set.ts from the source: every quoted
 * PascalCase string in src/ that is a Lucide export becomes a named import.
 * The same rule the `icons` gate applies, so the two cannot disagree. Run it
 * when the gate names a missing glyph.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LUCIDE = new Set(Object.keys(createRequire(import.meta.url)("lucide-react").icons));
const out = join(root, "src/components/ds/icon-set.ts");
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.tsx?$/.test(f) && !p.endsWith("icon-set.ts")) files.push(p); } };
walk(join(root, "src"));
const names = new Set();
for (const p of files) for (const m of readFileSync(p, "utf8").matchAll(/"([A-Z][A-Za-z0-9]*)"/g)) if (LUCIDE.has(m[1])) names.add(m[1]);
const list = [...names].sort();
writeFileSync(out, `/* The icons this codebase uses, imported by name so the bundler ships only
   these. The previous wrapper imported Lucide's whole \`icons\` map — 1,749
   glyphs, roughly half a megabyte of client JavaScript — to render about a
   hundred. A name outside this set renders the empty box the wrapper always
   drew, and the \`icons\` gate in check:ds fails on any quoted Lucide name the
   set does not carry. Generated by scripts/gen-icon-set.mjs — run it when the
   gate names a missing glyph; do not edit by hand. */
import {
${list.map((n) => `  ${n},`).join("\n")}
} from "lucide-react";

export const ICONS = {
${list.map((n) => `  ${n},`).join("\n")}
} as const;
`);
console.log(`icon-set: ${list.length} glyphs`);
